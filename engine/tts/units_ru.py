# Женский род: «одна тысяча», «две тонны». Для 1 и 2 подставляем слово, а не цифру,
# иначе numerals_ru прочитает «два тысячи».
FEMININE = {
    "тыс.", "шт.", "стр.", "с", "сек", "мин", "мс", "мкс", "нс", "т", "кал", "ккал", "л.с.",
}


def _feminine_prefix(raw_number: str, feminine: bool) -> str:
    if not feminine:
        return raw_number
    try:
        value = int(raw_number)
    except ValueError:
        return raw_number
    if value in (1, 2):
        return "одна" if value == 1 else "две"
    return raw_number


def _form(unit: str, raw_number: str) -> str:
    """Форма слова по числу: 1 миллисекунда, 2 миллисекунды, 5 миллисекунд."""
    if unit in COMPOUND:
        return COMPOUND[unit]
    forms = UNITS[unit]
    if isinstance(forms, str):
        return forms
    if "," in raw_number or "." in raw_number:
        return forms[1]
    try:
        value = abs(int(raw_number))
    except ValueError:
        return forms[2]
    return _plural(value, forms)


# Числа с «тыс.», «млн», «шт.» и дюймами: форма зависит от числа.
COUNT_FORMS: dict[str, tuple[str, str, str]] = {
    "тыс.": ("тысяча", "тысячи", "тысяч"),
    "млн": ("миллион", "миллиона", "миллионов"),
    "млрд": ("миллиард", "миллиарда", "миллиардов"),
    "шт.": ("штука", "штуки", "штук"),
    "чел.": ("человек", "человека", "человек"),
    "стр.": ("страница", "страницы", "страниц"),
    "дюйм": ("дюйм", "дюйма", "дюймов"),
}
COUNT_KEYS = sorted(COUNT_FORMS, key=len, reverse=True)
NUMBER_COUNT = re.compile(
    r"(?<![\w.,-])(-?\d+(?:[.,]\d+)?)\s*(" + "|".join(re.escape(key) for key in COUNT_KEYS) + r"|\"|″)(?![\w])"
)


def _count_repl(match: re.Match[str]) -> str:
    number, marker = match.group(1), match.group(2)
    if marker in ('"', '″'):
        marker = "дюйм"
    forms = COUNT_FORMS[marker]
    if "," in number or "." in number:
        return f"{_feminine_prefix(number, marker in FEMININE)} {forms[1]}"
    try:
        value = abs(int(number))
    except ValueError:
        return f"{_feminine_prefix(number, marker in FEMININE)} {forms[2]}"
    return f"{_feminine_prefix(number, marker in FEMININE)} {_plural(value, forms)}"


def expand_units(text: str) -> str:
    """Число + единица → число + слово; частые сокращения → фразы."""
    if not text:
        return text

    def unit_repl(match: re.Match[str]) -> str:
        number, unit = match.group(1), match.group(2)
        return f"{_feminine_prefix(number, unit in FEMININE)} {_form(unit, number)}"

    result = NUMBER_COUNT.sub(_count_repl, text)
    result = NUMBER_UNIT.sub(unit_repl, result)
    # Сокращения без числа: сначала длинные фразы, потом отдельные слова.
    for phrase in sorted(WORDS, key=len, reverse=True):
        spoken = WORDS[phrase]
        if phrase.endswith('.') or phrase.startswith('и '):
            # «т.д.», «в т.ч.» — в любом регистре, «США» и «РФ» — только как есть.
            flags = 0 if phrase.isupper() else re.IGNORECASE
            result = re.sub(r"(?<![\w])" + re.escape(phrase) + r"(?![\w])", spoken, result, flags=flags)
            continue
        result = re.sub(r"(?<![\w])" + re.escape(phrase) + r"(?![\w])", spoken, result)
    return result

# После перевода цифр в слова поправляем род числительного: «двадцать один тысяча»
# → «двадцать одна тысяча», «два тонны» → «две тонны».
FEMININE_NOUNS = (
    "тысяча", "тысячи", "тысяч", "тонна", "тонны", "тонн",
    "штука", "штуки", "штук", "страница", "страницы", "страниц",
    "секунда", "секунды", "секунд", "минута", "минуты", "минут",
    "миллисекунда", "миллисекунды", "миллисекунд",
    "микросекунда", "микросекунды", "микросекунд",
    "наносекунда", "наносекунды", "наносекунд",
    "калория", "калории", "калорий", "килокалория", "килокалории", "килокалорий",
)
FEMININE_FIX = re.compile(
    r"\b(один|два)(\s+(?:" + "|".join(FEMININE_NOUNS) + r"))\b"
)
FEMININE_REPLACEMENT = {"один": "одна", "два": "две"}


def fix_feminine(text: str) -> str:
    """Род числительного перед женским существительным."""
    if not text:
        return text
    return FEMININE_FIX.sub(lambda m: FEMININE_REPLACEMENT[m.group(1)] + m.group(2), text)